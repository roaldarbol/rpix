#' Speed between consecutive positions
#'
#' @param x,y Coordinates.
#' @param t Times.
#' @returns Speeds, one shorter than the inputs.
#' @export
speed <- function(x, y, t) {
  if (length(unique(lengths(list(x, y, t)))) != 1) {
    cli::cli_abort("{.arg x}, {.arg y} and {.arg t} must have the same length.")
  }
  sqrt(diff(x)^2 + diff(y)^2) / diff(t)
}
EOF

